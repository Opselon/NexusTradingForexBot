"""Generate the Windows PE version-info resource for PyInstaller builds.

WHY (WINDOWS-UX-001, taskbar identity & PE branding): PyInstaller embeds
the default Python version-info resource (or none at all) unless a
``--version-file`` is passed. Windows Explorer, the Task Manager and the
taskbar use the executable's PE version-info resources (``FileDescription``,
``ProductName``, ``CompanyName``) to brand the process image on disk.
When this metadata is missing or left as Python, Explorer and the taskbar
fall back to the generic interpreter identity.

TARGET VALUES:
    ProductName      = NexusTraderBot
    FileDescription  = NexusTraderBot
    InternalName     = NexusTraderBot
    OriginalFilename = NexusScalpEngine.exe
    CompanyName      = Opselon
    LegalCopyright   = Copyright (C) Opselon. All rights reserved.

BUILD-TIME ONLY: writes ``installer/version_info.txt`` in PyInstaller's
native VSVersionInfo format, consumed by ``scripts/build/build_release.ps1``
and the CI packaging workflow via ``--version-file``.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUTPUT = REPO / "installer" / "version_info.txt"


def _parse_version(version_str: str) -> tuple[int, int, int, int]:
    m = re.match(r"^v?(\d+)\.(\d+)\.(\d+)", version_str)
    if not m:
        return (9, 0, 0, 0)
    return (int(m.group(1)), int(m.group(2)), int(m.group(3)), 0)


def generate_version_info(
    version: str = "9.0.14", output: Path = OUTPUT, original_filename: str = "NexusScalpEngine.exe"
) -> Path:
    maj, min_, patch, build = _parse_version(version)
    ver_tuple = f"({maj}, {min_}, {patch}, {build})"
    ver_str = f"{maj}.{min_}.{patch}.{build}"

    content = f"""# UTF-8
#
# VSVersionInfo resource file for PyInstaller (Windows PE metadata)
# Generated by scripts/build/generate_version_info.py — do not edit manually.

VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={ver_tuple},
    prodvers={ver_tuple},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          '040904B0',
          [
            StringStruct('CompanyName', 'Opselon'),
            StringStruct('FileDescription', 'NexusTraderBot'),
            StringStruct('FileVersion', '{ver_str}'),
            StringStruct('InternalName', 'NexusTraderBot'),
            StringStruct('LegalCopyright', 'Copyright (C) Opselon. All rights reserved.'),
            StringStruct('OriginalFilename', '{original_filename}'),
            StringStruct('ProductName', 'NexusTraderBot'),
            StringStruct('ProductVersion', '{ver_str}')
          ]
        )
      ]
    ),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(content, encoding="utf-8")
    print(f"[version-info] wrote {output} (version {ver_str}, Product=NexusTraderBot)")
    return output


if __name__ == "__main__":
    v = "9.0.14"
    if len(sys.argv) > 1:
        v = sys.argv[1]
    else:
        # Read canonical version from pyproject.toml if available
        pyproj = REPO / "pyproject.toml"
        if pyproj.exists():
            m = re.search(r'^version\s*=\s*"([^"]+)"', pyproj.read_text(encoding="utf-8"), re.M)
            if m:
                v = m.group(1)
    generate_version_info(v)
