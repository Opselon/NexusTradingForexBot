"""AI failure triage for CI/CD Telegram summaries (BUG-300).

The Telegram feed already delivers WHAT failed (structured run/release/PR
summaries built from ci-results/). This module adds WHY — a short,
pro-prompt-driven root-cause analysis generated by the operator-configured
OpenAI-compatible endpoint (GitHub Actions secrets ``AI_HOST`` / ``AI_KEY``,
optionally ``AI_MODEL``) — and a hard rule that the notification must
still go out when the AI is not usable.

Reachability gate (the "timer" contract)
-----------------------------------------
Before ANY completion call we probe ``{AI_HOST}/models``:

1. TCP connect phase capped by ``AI_PROBE_CONNECT_SEC`` (default 2.0 s) —
   an unroutable host fails fast instead of hanging the notify step.
2. Full response budget ``AI_PROBE_TIMEOUT_SEC`` (default 4.0 s); HTTP 200
   with a parseable model list means the endpoint is alive.
3. A healthy probe that took longer than ``AI_PROBE_SLOW_SEC`` (default
   2.5 s) is classified SLOW — completion is still attempted once, then
   the endpoint is marked degraded for the rest of the process (circuit
   opened) so a half-alive host cannot stall every notification lane.
4. Probe verdicts are cached per (scheme,host,port) for
   ``AI_PROBE_CACHE_SEC`` (default 120 s) — many notifies in one job share
   one probe instead of re-paying the timer.

Fallback chain (never blocks, never silent)
-------------------------------------------
* endpoint not configured            -> RULES fallback, provenance UNCONFIGURED
* probe refused/timed out/HTTP error -> RULES fallback, provenance DOWN
* completion failed/timeout/bad body -> RULES fallback, provenance CHAT_FAILED
* rules found nothing to say         -> still delivered with provenance
                                        RULES_EMPTY so the gate state is
                                        visible on the channel

Safety
------
* Outbound text is redacted (``redact_secrets``) and additionally scrubbed
  of the literal configured secret values (AI_KEY / bot token) before it
  leaves the process — the AI host never sees repo credentials.
* The AI endpoint's response is HTML-escaped by the caller before it can
  reach Telegram (prompt-injection to a messaging channel is treated as
  untrusted content).
* ``AI_HOST`` over plain http is allowed (operator choice) but flagged
  ``PLAINTEXT_HOST`` in the result so logs/docs keep the audit trail.
* Every public function returns a dict/JSON path; nothing raises into CI.
"""

