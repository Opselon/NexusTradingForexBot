# Completion call
# ---------------------------------------------------------------------------


def _parse_sse(text: str) -> str:
    """Join streamed delta/content fragments when the host SSEs despite stream=false."""
    parts: list[str] = []
    for line in text.splitlines():
        if not line.startswith("data:"):
            continue
        payload = line[5:].strip()
        if not payload or payload == "[DONE]":
            continue
        try:
            obj = json.loads(payload)
        except Exception:
            continue
        for ch in obj.get("choices") or []:
            delta = ch.get("delta") or {}
            piece = delta.get("content") or ""
            if piece:
                parts.append(piece)
    return "".join(parts)


def chat_completion(
    ep: Endpoint, system_prompt: str, user_prompt: str, *, timeout_sec: float | None = None
) -> tuple[str | None, str]:
    """Single non-streaming chat call. Returns (text, error); exactly one is None-ish."""
    body = json.dumps(
        {
            "model": ep.model,
            "stream": False,
            "max_tokens": 1400,
            "temperature": 0.2,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
        }
    ).encode("utf-8")
    req = urllib.request.Request(
        ep.host + "/chat/completions",
        data=body,
        headers={
            "Authorization": f"Bearer {ep.key}",
            "Content-Type": "application/json",
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout_sec or CHAT_TIMEOUT_SEC) as resp:
            raw = resp.read(600_000).decode("utf-8", "replace")
    except urllib.error.HTTPError as err:
        return None, f"HTTP {err.code}"
    except TimeoutError:  # socket.timeout is an alias on 3.10+
        return None, "timeout"
    except Exception as err:
        return None, str(err)[:160]

    try:
        obj = json.loads(raw)
        text = ((obj.get("choices") or [{}])[0].get("message") or {}).get("content") or ""
        if not text.strip():
            text = _parse_sse(raw)
    except Exception:
        text = _parse_sse(raw)
    # strip reasoning blocks some hosts leak into content
    text = re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL).strip()
    if not text:
        return None, "empty completion"
    return text[:4000], ""


