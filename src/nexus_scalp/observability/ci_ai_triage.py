def _redactor():
    try:
        from nexus_scalp.observability.telegram_transport import redact_secrets

        return redact_secrets
    except Exception:  # offline import failure -> local fallback patterns

        def redact_secrets(text: str) -> str:
            out = re.sub(r"sk-[A-Za-z0-9_\-]{12,}", "[REDACTED_SK]", text)
            out = re.sub(r"\d{8,10}:[A-Za-z0-9_-]{25,}", "[REDACTED_BOT_TOKEN]", out)
            return re.sub(
                r"(?i)(password|passwd|secret|api[_-]?key|token|auth|credential)\s*[=:]\s*\S+",
                r"\1=[REDACTED]",
                out,
            )

    return redact_secrets


def sanitize(text: str, ep: Endpoint | None = None) -> str:
    """Redact secret shapes, then strip literal configured secret values."""
    out = _redactor()(text or "")
    if ep:
        for literal in (
            ep.key,
            os.environ.get("TELEGRAM_BOT_TOKEN", ""),
            os.environ.get("GITHUB_TOKEN", ""),
        ):
            if literal and len(literal) >= 8:
                out = out.replace(literal, "[REDACTED]")
    return out[:MAX_CONTEXT_CHARS]


def load_context(path: str | Path) -> dict[str, Any]:
    try:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {"raw": data}
    except Exception as err:
        return {"context_load_error": str(err)[:120]}


