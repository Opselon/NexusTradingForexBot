# Deterministic fallback (the "find the problem without AI" rules)
# ---------------------------------------------------------------------------

_RULES: list[tuple[str, str, str]] = [
    # (regex over serialized evidence, verdict clause, cheapest first check)
    (
        r"requirements\.lock|Dependency drift|pyproject",
        "dependency lock drift (lock vs pyproject mismatch)",
        "python scripts/ci/check_dependency_drift.py",
    ),
    (
        r"ruff format|RUFF_FORMAT_RC|would be reformatted",
        "format gate red — downstream mypy/pytest checks are BLOCKED, not failed",
        "ruff format --check .",
    ),
    (
        r"eol|CRLF|LF will be replaced",
        "likely CRLF/autocrlf noise (repo is core.autocrlf=true)",
        "git diff --stat after normalizing line endings",
    ),
    (
        r"429|Retry-After|TELEGRAM_RATE_LIMIT",
        "provider/transport rate limit on the notify lane itself",
        "check notifier health_state()",
    ),
    (
        r"Merge conflict|CONFLICT \(",
        "branch is on a stale base vs main (squash-carrier drift)",
        "git merge origin/main on an integration copy",
    ),
    (
        r"CodeQL|redos|ReDoS|http-response-splitting",
        "code-scanning alert class — sanitizer must stay linear-time",
        "re-run CodeQL locally on the touched file",
    ),
    (
        r"401|UNAUTHORIZED|auth",
        "auth bootstrap/cookie regression shape (WEB-AUTH-P0 family)",
        "tests/unit/test_bug267_*",
    ),
    (
        r"test_start_smoke|model\.pt|SAFE_MODE|provision",
        "fresh-install/provisioning gate (model acquisition before start)",
        "nexus start on a clean profile per BUG-298 lanes",
    ),
    (
        r"exitcode: (124|137)|Timeout|SIGTERM",
        "runner timeout / OOM rather than an assertion failure",
        "compare runtime vs job timeout-minutes; check memory of the suite",
    ),
    (
        r"curl|network|Connection reset|getaddrinfo",
        "external network flake (known chronic on this host)",
        "gh run rerun --failed",
    ),
]


def rules_analysis(context: dict[str, Any]) -> str:
    """Deterministic one-paragraph fallback derived from the evidence text."""
    blob = json.dumps(context, default=str)
    hits: list[tuple[str, str]] = []
    for pattern, verdict, check in _RULES:
        if re.search(pattern, blob, flags=re.IGNORECASE):
            hits.append((verdict, check))
    if not hits:
        return ""
    verdict, check = hits[0]
    lines = [
        f"WHY: {verdict}",
        "EVIDENCE: rule pattern matched in the run evidence (no AI available)",
        "VERDICT: INVESTIGATE",
        "CHECK: " + " | ".join(c for _, c in hits[:3]),
        "CONFIDENCE: low (deterministic fallback — AI endpoint unavailable)",
    ]
    return "\n".join(lines)


