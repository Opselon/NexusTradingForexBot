AI_HOST_ENV = "AI_HOST"
AI_KEY_ENV = "AI_KEY"
AI_MODEL_ENV = "AI_MODEL"
DEFAULT_MODEL = "coding"


def _float_env(name: str, default: float) -> float:
    try:
        return float(os.environ.get(name, "") or default)
    except ValueError:
        return default


PROBE_CONNECT_SEC = _float_env("AI_PROBE_CONNECT_SEC", 2.0)
#: /models responses can be large slow-to-serialize even on healthy combo
#: hosts (observed ~5 s for a 500 KB catalog) — the connect timer is what
#: catches DEAD hosts fast; this budget only bounds the response phase.
PROBE_TIMEOUT_SEC = _float_env("AI_PROBE_TIMEOUT_SEC", 8.0)
PROBE_SLOW_SEC = _float_env("AI_PROBE_SLOW_SEC", 2.5)
PROBE_CACHE_SEC = _float_env("AI_PROBE_CACHE_SEC", 120.0)
CHAT_TIMEOUT_SEC = _float_env("AI_CHAT_TIMEOUT_SEC", 45.0)
#: Hard character budget for outbound context (prompt sizing + cost bound).
MAX_CONTEXT_CHARS = int(_float_env("AI_MAX_CONTEXT_CHARS", 10000))

#: provenance vocabulary (stable — tests and docs pin these strings)
PROV_AI = "AI"
PROV_UNCONFIGURED = "AI_UNCONFIGURED"
PROV_DOWN = "AI_UNREACHABLE"
PROV_CHAT_FAILED = "AI_CHAT_FAILED"
PROV_RULES_EMPTY = "AI_RULES_EMPTY"

#: short aliases (stable vocabulary for tests/docs)
AI = PROV_AI


@dataclass
class Endpoint:
    host: str
    key: str
    model: str
    plaintext: bool = False

    @classmethod
    def from_env(cls) -> Endpoint | None:
        host = (os.environ.get(AI_HOST_ENV) or "").strip().rstrip("/")
        key = (os.environ.get(AI_KEY_ENV) or "").strip()
        if not host or not key:
            return None
        if not host.startswith(("http://", "https://")):
            host = "https://" + host
        model = (os.environ.get(AI_MODEL_ENV) or "").strip() or DEFAULT_MODEL
        return cls(host=host, key=key, model=model, plaintext=host.startswith("http://"))


# ---------------------------------------------------------------------------
# Reachability gate (probe + timers + circuit cache)
# ---------------------------------------------------------------------------

#: cache key -> (monotonic_time, verdict dict, ttl_sec). Negative verdicts
#: cache SHORT (15 s) so flaky/intermittent hosts get retried quickly —
#: combo endpoints frequently 500/timeout on 1-in-N calls; positive verdicts
#: cache for PROBE_CACHE_SEC so N notifies in one job pay the probe once.
_PROBE_CACHE: dict[str, tuple[float, dict[str, Any], float]] = {}


def _cache_key(ep: Endpoint) -> str:
    p = urlparse(ep.host)
    return f"{p.scheme}://{p.hostname}:{p.port or (80 if p.scheme == 'http' else 443)}"


def _tcp_reachable(url: str, connect_sec: float) -> tuple[bool, float]:
    """Phase-1 timer: pure socket connect, no HTTP, no TLS handshake wait."""
    p = urlparse(url)
    host = p.hostname or ""
    port = p.port or (80 if p.scheme == "http" else 443)
    t0 = time.monotonic()
    try:
        with socket.create_connection((host, port), timeout=connect_sec):
            return True, time.monotonic() - t0
    except OSError:
        return False, time.monotonic() - t0


def probe_reachable(ep: Endpoint, *, force: bool = False) -> dict[str, Any]:
    """Gate check: status OK | SLOW_OK | TCP_REFUSED | TIMEOUT | HTTP_ERROR | ERROR.

    OK/SLOW_OK mean completions may be attempted (SLOW_OK once before the
    circuit opens). Everything else means: use the fallback right now.
    """
    key = _cache_key(ep)
    now = time.monotonic()
    if not force:
        hit = _PROBE_CACHE.get(key)
        if hit and now - hit[0] < hit[2]:
            cached = dict(hit[1], cached=True)
            # circuit open semantics: a SLOW verdict is attempted once (uncached
            # pass); a CACHED slow verdict means "already tried, still slow" ->
            # degrade to fallback for the rest of the TTL window.
            if cached.get("status") == "SLOW_OK":
                cached["status"] = "SLOW_DEGRADED"
            return cached

    verdict: dict[str, Any] = {
        "status": "ERROR",
        "connect_sec": None,
        "total_sec": None,
        "models": 0,
        "error": "",
    }
    reachable, connect_sec = _tcp_reachable(ep.host, PROBE_CONNECT_SEC)
    verdict["connect_sec"] = round(connect_sec, 3)
    if not reachable:
        verdict["status"] = "TCP_REFUSED"
        verdict["error"] = "connect refused/failed"
        _PROBE_CACHE[key] = (now, verdict, 15.0)
        return dict(verdict)

    t0 = time.monotonic()
    req = urllib.request.Request(
        ep.host + "/models",
        headers={"Authorization": f"Bearer {ep.key}", "Accept": "application/json"},
    )
    try:
        with urllib.request.urlopen(req, timeout=PROBE_TIMEOUT_SEC) as resp:
            verdict["status"] = "OK" if resp.status == 200 else "HTTP_ERROR"
            # Read a bounded head only: some hosts serialize the WHOLE model
            # catalog (500KB+) and a full read blows the probe timer budget on
            # healthy endpoints. Presence of the list key is enough evidence.
            head = resp.read(4096).decode("utf-8", "replace")
            if verdict["status"] == "OK" and '"data"' not in head:
                verdict["status"] = "HTTP_ERROR"
                verdict["error"] = "models list shape unexpected"
    except urllib.error.HTTPError as err:
        verdict["status"] = "HTTP_ERROR"
        verdict["error"] = f"HTTP {err.code}"
    except TimeoutError:  # socket.timeout is an alias on 3.10+
        verdict["status"] = "TIMEOUT"
        verdict["error"] = f">{PROBE_TIMEOUT_SEC}s response budget"
    except Exception as err:  # DNS, TLS, reset...
        verdict["status"] = "ERROR"
        verdict["error"] = str(err)[:160]
    total = time.monotonic() - t0
    verdict["total_sec"] = round(total, 3)
    if verdict["status"] == "OK" and total > PROBE_SLOW_SEC:
        verdict["status"] = "SLOW_OK"
    ttl = PROBE_CACHE_SEC if verdict["status"] in ("OK", "SLOW_OK") else 15.0
    _PROBE_CACHE[key] = (now, verdict, ttl)
    return dict(verdict, cached=False)


