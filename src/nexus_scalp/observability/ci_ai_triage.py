@dataclass
class Analysis:
    kind: str
    text: str
    provenance: str
    model: str = ""
    probe: dict[str, Any] = field(default_factory=dict)
    plaintext_host: bool = False

    def to_result(self, delivered: bool) -> dict[str, Any]:
        return {
            "ok": bool(self.text),
            "kind": self.kind,
            "provenance": self.provenance,
            "model": self.model or None,
            "delivered": delivered,
            "plaintext_host": self.plaintext_host or None,
            "probe": self.probe,
            "chars": len(self.text),
        }


def analyze(kind: str, context: dict[str, Any]) -> Analysis:
    """AI summary with the reachability gate + guaranteed rules fallback.

    Never raises; always returns an Analysis (text may be empty only with
    RULES_EMPTY provenance, which the caller still reports).
    """
    ep = Endpoint.from_env()
    if ep is None:
        return Analysis(
            kind,
            rules_analysis(context),
            PROV_UNCONFIGURED if rules_analysis(context) else PROV_RULES_EMPTY,
            plaintext_host=False,
        )
    base = Analysis(kind, "", "", model=ep.model, plaintext_host=ep.plaintext)
    probe = probe_reachable(ep)
    base.probe = {k: probe.get(k) for k in ("status", "connect_sec", "total_sec", "cached")}
    if probe["status"] not in ("OK", "SLOW_OK"):
        base.text = rules_analysis(context)
        base.provenance = PROV_DOWN if base.text else PROV_RULES_EMPTY
        return base
    user = (
        PROMPTS.get(kind, PROMPTS["ci-failure"])
        + "\n\nJSON EVIDENCE:\n"
        + sanitize(json.dumps(context, default=str, sort_keys=True)[:MAX_CONTEXT_CHARS], ep)
    )
    text, _err = chat_completion(ep, _SYSTEM, user)
    if not text:
        # combo hosts flake intermittently (observed 1-in-3 on the live
        # endpoint: empty bodies, resets, 5xx between success streaks):
        # ONE bounded retry for any transient failure before degrading.
        text, _retry_err = chat_completion(
            ep, _SYSTEM, user, timeout_sec=max(15.0, CHAT_TIMEOUT_SEC * 0.6)
        )
    if not text:
        base.text = rules_analysis(context)
        base.provenance = PROV_CHAT_FAILED if base.text else PROV_RULES_EMPTY
        return base
    base.text = text
    base.provenance = PROV_AI
    return base


