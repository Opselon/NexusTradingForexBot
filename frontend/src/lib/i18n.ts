/**
 * i18n — port of the main dashboard's UX_I18N layer (Web/ux_i18n.js, CHG-0048).
 *
 * Same dictionaries (EN identity + FA/DE/ES/AR), same key contract, same
 * storage rule (localStorage = UI preference ONLY, never NSE state), same RTL
 * handling (fa/ar set dir=rtl). t(key, fallback, vars) returns the fallback —
 * which is the English source string — when no dictionary entry exists, so a
 * missing translation can never blank the UI.
 */

export type Lang = "en" | "fa" | "de" | "es" | "ar";

const LANG_KEY = "nexus.ui.lang"; // shared with the legacy dashboard: one preference
const RTL: Partial<Record<Lang, boolean>> = { fa: true, ar: true };

type Dict = Record<string, string>;

/** One key's translations. The four non-English languages are REQUIRED at
 *  compile time (en stays identity: its source string is the call-site
 *  fallback of t()). An optional `en` entry is honored when present. */
export interface MessageEntry {
  fa: string;
  de: string;
  es: string;
  ar: string;
  en?: string;
}

/** A scope's message table (see <scope>/i18n.ts + lib/i18nMessages.ts). */
export type FeatureMessages = Record<string, MessageEntry>;

/** Dev-only missing-key diagnostics (§12): a key present nowhere warns ONCE
 *  with the English fallback it is showing. Production stays silent and
 *  renders the fallback cleanly — the warn never runs in a production build
 *  (import.meta.env.DEV is false there; guarded for non-Vite importers too). */
const DEV =
  typeof import.meta !== "undefined" &&
  typeof (import.meta as { env?: { DEV?: boolean } }).env !== "undefined" &&
  (import.meta as { env?: { DEV?: boolean } }).env?.DEV === true;
const warnedMissing = new Set<string>();

/** Runtime lookup filled by registerMessages() — scoped messages win over
 *  the legacy chrome DICTS below. */
const MAP: Record<string, Partial<Record<Lang, string>>> = {};

/** Register one scope's messages (first registration wins; a duplicate key
 *  warns and keeps the earlier entry so a later scope can never silently
 *  shadow shared chrome keys). Called once per scope from i18nMessages.ts. */
export function registerMessages(msgs: Record<string, Partial<Record<Lang, string>>>): void {
  for (const [k, v] of Object.entries(msgs)) {
    if (MAP[k] !== undefined) {
      console.warn(`[i18n] duplicate key ignored: ${k}`);
      continue;
    }
    MAP[k] = v;
  }
}

